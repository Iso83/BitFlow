#pragma region HashTicket
void HashTicket::Normal(const unsigned char* input, unsigned char hash[32], unsigned steps)
{
	SHA256 ctx;
	ctx.Init();
	ctx.Update(input, strlen((const char*)input), steps);
	ctx.Final(hash, steps);
}

bool HashTicket::Process(unsigned char *input, unsigned steps, void(*transform)(SHA256 *buffer, const unsigned __int8 data[64], unsigned steps))
{
	Normal(input, target, steps);

	SHA256 ctx;
	ctx.Init();
	SHA256::Update(&ctx, input, strlen((const char*)input), steps, transform);
	SHA256::Final(&ctx, result, steps, transform);

	return Passed();
}

bool HashTicket::Passed() const
{
	return IXAlgo::Compare<unsigned char, unsigned>(target, 32, result, 32, false, false) == IXAlgo::CmpRes::Equal;
}
