#pragma region S1
void Transform_S1(SHA256 *ctx, const unsigned __int8 data[64], unsigned steps)
{
	assert(steps == 1);

	unsigned __int32 a, b, c, d, e, f, g, h, t1, t2, m[64];

	a = ctx->state[0];
	b = ctx->state[1];
	c = ctx->state[2];
	d = ctx->state[3];
	e = ctx->state[4];
	f = ctx->state[5];
	g = ctx->state[6];
	h = ctx->state[7];

	// Round
	t1 = h + EP1(e) + CH(e, f, g) + k[0] + ((data[0] << 24) | (data[1] << 16) | (data[2] << 8) | (data[3]));
	t2 = EP0(a) + MAJ(a, b, c);

	ctx->state[7] += ctx->state[6];
	ctx->state[6] += ctx->state[5];
	ctx->state[5] += ctx->state[4];
	ctx->state[4] += ctx->state[3] + t1;

	ctx->state[3] += ctx->state[2];
	ctx->state[2] += ctx->state[1];
	ctx->state[1] += ctx->state[0];
	ctx->state[0] += t1 + t2;
}
